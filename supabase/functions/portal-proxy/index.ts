const nprocureClient = Deno.createHttpClient({ caCerts: [SECTIGO_INTERMEDIATE] });

Deno.serve(async (req) => {
  const secret = Deno.env.get("PORTAL_PROXY_SECRET")?.trim(); // dashboard pastes may add a newline
  if (!secret || req.headers.get("x-proxy-secret") !== secret) {
    return Response.json({ error: "forbidden" }, { status: 403 });
  }
  if (req.method !== "POST") return Response.json({ error: "POST only" }, { status: 405 });

  let target: { url?: string; method?: string; headers?: Record<string, string>; body?: string };
  let url: URL;
  try {
    target = await req.json();
    url = new URL(target.url ?? "");
  } catch {
    return Response.json({ error: "body must be JSON with a valid url" }, { status: 400 });
  }
  if (url.protocol !== "https:" || !ALLOWED_HOSTS.has(url.hostname)) {
    return Response.json({ error: `host not allowed: ${url.hostname}` }, { status: 400 });
  }

  try {
    const res = await fetch(url, {
      method: target.method ?? "GET",
      headers: target.headers ?? {},
      body: target.body ?? undefined,
      signal: AbortSignal.timeout(30000),
      ...(url.hostname === "tender.nprocure.com" && { client: nprocureClient }),
    });
    return Response.json({ status: res.status, setCookies: res.headers.getSetCookie(), body: await res.text() });
  } catch (e) {
    return Response.json({ error: String(e) }, { status: 502 });
  }
});
